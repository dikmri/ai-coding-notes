// キャラの名前を自動で作る表（設計書 §1: 名前は自動。個人情報を集めない）
// 頭 + 中（空のことが多い）+ 尾 をつないだカタカナの名前。実在の人名や既存の作品の名前に
// なりやすい音を避けて部品を選び、それでもできてしまう名前は banned で弾く。
// 同じ名前の客がいるときの扱い（番号を足すなど）はサーバーの係が決める。

export const nameParts = Object.freeze({
  heads: [
    'アズ', 'イルヴ', 'ヴェス', 'エルド', 'オルム', 'カゼ', 'キリュ', 'グラム', 'ケルス', 'ゼフィ',
    'セラ', 'ティル', 'ドゥナ', 'ナグ', 'ニェ', 'ハロ', 'フィン', 'ベルカ', 'ミュレ', 'ユグ',
    'ラザ', 'リュオ', 'ルグ', 'レムナ', 'ロゥ', 'ヴァル', 'シェラ', 'ソルヴ', 'ザイ', 'トゥル',
  ],
  mids: ['', '', '', '', 'ラ', 'リ', 'ン', 'ディ', 'ヴィ', 'ス', 'ノ'],
  tails: [
    'ア', 'エル', 'オン', 'ス', 'ト', 'ナ', 'ネ', 'ド', 'リス', 'ロ',
    'ム', 'ガ', 'ディア', 'フェン', 'ヴァ', 'ゼル', 'ミエ', 'ルク', 'ジュ', 'オル',
  ],
  minLen: 3,
  maxLen: 8,
  // 実在の人名・地名や、よく知られた作品の登場人物と同じになる名前
  banned: [
    'エルドラド', 'セラス', 'セラフィン', 'カゼト', 'フィンナ', 'ゼフィロス', 'ハロス', 'ラザロ', 'ラザルス',
    'ヴァルナ', 'ユグドラ', 'セラナ', 'グラムス', 'ベルカナ', 'シェラト', 'ティルト', 'ルグナ', 'ザイオン',
    'アズエル', 'ザイド', 'ナグア', 'セラフ',
  ],
});

// rand は 0 以上 1 未満を返す関数。同じ並びなら同じ名前になる。
export function makeName(rand = Math.random) {
  const { heads, mids, tails, minLen, maxLen, banned } = nameParts;
  const pick = (a) => a[Math.floor(rand() * a.length)];
  for (let i = 0; i < 30; i++) {
    const n = pick(heads) + pick(mids) + pick(tails);
    if (n.length >= minLen && n.length <= maxLen && !banned.includes(n)) return n;
  }
  return 'ナナシノタビビト'.slice(0, maxLen);
}
